#!/usr/bin/env python3
"""Write the deploy yaml from the branch's own aura_omni*.yaml.

Only model paths and per-stage `devices` change; every tuned knob stays as
upstream ships it. Standard library only.

  python make_yaml.py <upstream yaml> <out yaml> --aura P --asr P --tts P --stage1-dev D --side-dev D
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROLE_BY_STAGE = {0: "asr", 1: "aura", 2: "tts", 3: "tts"}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("src")
    p.add_argument("out")
    p.add_argument("--aura", required=True)
    p.add_argument("--asr", required=True)
    p.add_argument("--tts", required=True)
    p.add_argument("--stage1-dev", required=True, help="device index for Stage1 (AURA)")
    p.add_argument("--side-dev", required=True, help="device index for ASR / Talker / Code2Wav")
    a = p.parse_args()
    paths = {"asr": a.asr, "aura": a.aura, "tts": a.tts}

    text = Path(a.src).read_text(encoding="utf-8")
    parts = re.split(r"(?m)^(  - stage_id: \d+\s*$)", text)
    out = [parts[0]]
    seen = set()
    for head, body in zip(parts[1::2], parts[2::2]):
        stage = int(re.search(r"\d+", head).group())
        role = ROLE_BY_STAGE.get(stage)
        if role is None:
            raise SystemExit(f"unexpected stage {stage} in {a.src}")
        dev = a.stage1_dev if stage == 1 else a.side_dev
        body, n_dev = re.subn(r'(?m)^(    devices: )"[^"]*"', lambda m: f'{m.group(1)}"{dev}"', body)
        body, n_model = re.subn(r"(?m)^(    model: ).*$", lambda m: m.group(1) + paths[role], body)
        if n_dev != 1 or n_model != 1:
            raise SystemExit(f"stage {stage}: expected one devices and one model line (got {n_dev}, {n_model})")
        seen.add(stage)
        out += [head, body]
    if seen != {0, 1, 2, 3}:
        raise SystemExit(f"expected stages 0-3 in {a.src}, found {sorted(seen)}")

    header = (
        f"# Generated by aura.sh from {Path(a.src).name}; only model paths and devices differ.\n"
        "# Devices are indices inside CUDA_VISIBLE_DEVICES.\n"
    )
    Path(a.out).write_text(header + "".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
